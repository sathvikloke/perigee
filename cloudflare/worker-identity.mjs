// Worker code identity, computed from the files Wrangler actually bundles.
//
// Run by Wrangler as the custom build step (wrangler.jsonc "build.command") before
// every `wrangler dev` / `wrangler deploy`, and mirrored by cloudflare/build.py.
// Writes cloudflare/build/worker-identity.js, which src/app.js imports and reports
// as the X-Perigee-Worker header, so a release check can verify the DEPLOYED Worker
// code, not only the static files. No timestamps: identical code, identical digest.
//
// Digest = SHA-256 over sorted "path<TAB>sha256(file)" lines (joined by "\n") for
// cloudflare/src/**/*.js and cloudflare/wrangler.jsonc, paths relative to the repo root.
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url)); // cloudflare/
const REPO = path.dirname(HERE);

function jsFiles(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) out.push(...jsFiles(p));
    else if (name.endsWith(".js")) out.push(p);
  }
  return out;
}

export function workerIdentity(srcDir = path.join(HERE, "src"), configFile = path.join(HERE, "wrangler.jsonc")) {
  const files = [...jsFiles(srcDir), configFile];
  const lines = files
    .map((f) => `${path.relative(REPO, f).split(path.sep).join("/")}\t${createHash("sha256").update(readFileSync(f)).digest("hex")}`)
    .sort();
  return { digest: createHash("sha256").update(lines.join("\n")).digest("hex"), files: lines.length };
}

export function moduleSource(id) {
  return `// Generated by cloudflare/worker-identity.mjs / cloudflare/build.py. Do not edit.\nexport const WORKER_DIGEST = ${JSON.stringify(id.digest)};\nexport const WORKER_FILES = ${id.files};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const id = workerIdentity();
  mkdirSync(path.join(HERE, "build"), { recursive: true });
  writeFileSync(path.join(HERE, "build", "worker-identity.js"), moduleSource(id));
  console.log(`perigee worker identity ${id.digest} (${id.files} files)`);
}
